def test_render_width_kwarg_overrides_raw_terminal_size():
    # Regression shape mirroring VIEWMD-0043's own pie-chart bug: `width`
    # must reach the renderer, not be re-queried from the terminal directly.
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    out_narrow = render(chart, use_ascii=False, color=False, width=60)
    out_wide = render(chart, use_ascii=False, color=False, width=200)
    assert out_narrow != out_wide
    widest_narrow = max(len(line) for line in out_narrow.splitlines())
    widest_wide = max(len(line) for line in out_wide.splitlines())
    assert widest_narrow < widest_wide


def test_default_box_width_scales_with_target_width():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    assert _default_box_width(chart, 60) < _default_box_width(chart, 100) < \
        _default_box_width(chart, 200)


def test_default_box_width_floors_at_minimum_for_very_narrow_target():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    assert _default_box_width(chart, 1) >= 10


def test_default_box_width_grows_to_fit_a_long_title():
    # Regression: the title used to be ignored by the sizing math entirely
    # (only y-axis label length was considered), so a title longer than the
    # width-derived box would silently overflow past target_width even
    # though requirement 7 names the title explicitly as something the box
    # must fit.
    chart = parse(
        "quadrantChart\n"
        "title This Is A Deliberately Very Long Title For A Narrow Render Width\n"
        "x-axis Lo --> Hi\ny-axis Lo --> Hi\n"
    )
    narrow_target = 40
    qw = _default_box_width(chart, narrow_target)
    box_width = qw * 2 + 3
    assert box_width >= string_width(chart.title)


def test_title_line_does_not_overflow_when_it_fits_the_box():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())  # short title
    out = render(chart, use_ascii=False, color=False, width=68)
    title_line = out.splitlines()[0]
    other_line = out.splitlines()[2]  # a border row, box_width + left_pad
    assert len(title_line) == len(other_line)
