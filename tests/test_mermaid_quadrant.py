"""Tests for the quadrant-chart renderer (VIEWMD-0047).

No upstream reference implementation to differentially test against (like
pie, unlike flowchart/sequence/ER) -- termaid's own free-floating axis-cross
rendering was a useful cross-check during design (see the issue's Design
notes), not an oracle, and it renders a different (borderless) layout. The
plain-box fixture in tests/fixtures/mermaid_quadrant/ is hand-authored/
generated by this renderer itself and visually verified, same posture as the
pie chart's own bar-chart fixtures. Colored rendering embeds real ANSI
escapes whose exact byte layout isn't pinned -- tested for the structural
properties the issue's Acceptance section calls for instead (per-quadrant
tint/background, a point's explicit color overriding its quadrant's
fallback, and color being strictly additive over the plain layout).
"""

from __future__ import annotations

import re
from pathlib import Path

from viewmd.mermaid.quadrant.parser import parse
from viewmd.mermaid.quadrant.renderer import _default_box_width, render
from viewmd.mermaid.textutil import width as string_width

FIXTURES = Path(__file__).parent / "fixtures" / "mermaid_quadrant"

_ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")


def _strip_ansi(s: str) -> str:
    return _ANSI_RE.sub("", s)


# ---------------------------------------------------------------------------
# Plain box: golden fixture (requirement 6)
# ---------------------------------------------------------------------------


def test_priority_matrix_matches_fixture():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    out = render(chart, use_ascii=False, color=False, width=68)
    assert out == (FIXTURES / "priority_matrix.out").read_text()


def test_plain_box_has_no_ansi_when_color_disabled():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    out = render(chart, use_ascii=False, color=False, width=68)
    assert _ANSI_RE.search(out) is None


def test_ascii_mode_uses_plus_and_dash_border():
    chart = parse((FIXTURES / "priority_matrix.mmd").read_text())
    out = render(chart, use_ascii=True, color=False, width=68)
    assert "┌" not in out
    assert "+" in out and "-" in out
    assert "●" not in out and "*" in out


# ---------------------------------------------------------------------------
# Collision handling (requirement 9 / Non-goals)
# ---------------------------------------------------------------------------


def test_two_close_points_render_without_crashing():
    chart = parse((FIXTURES / "collision.mmd").read_text())
    out = render(chart, use_ascii=False, color=False, width=68)
    plain = _strip_ansi(out)
    assert "Alpha" in plain
    assert "Beta" in plain


