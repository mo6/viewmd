def test_empty_points_still_renders_quadrant_labels_and_axes():
    chart = parse("quadrantChart\ntitle T\nx-axis Lo --> Hi\ny-axis Lo --> Hi\n"
                  "quadrant-1 A\nquadrant-2 B\nquadrant-3 C\nquadrant-4 D\n")
    out = render(chart, use_ascii=False, color=False, width=68)
    for text in ("T", "Lo", "Hi", "A", "B", "C", "D"):
        assert text in out


