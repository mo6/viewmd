_SALES = (
    "xychart-beta\n"
    '    title "Sales"\n'
    "    x-axis [Q1, Q2, Q3, Q4]\n"
    "    y-axis 0 --> 100\n"
    "    bar [40, 55, 70, 90]\n"
)


def test_plot_width_at_fifty_percent_floor():
    # 4 short categories: content min is well below 50% of W=80, so the
    # plot sits on the floor (40 columns) with height close to width (1:1).
    chart = parse(_SALES)
    out = render(chart, use_ascii=False, width=80)
    pw = _inner_plot_width(out)
    ph = _plot_height(out)
    assert pw == 40
    assert ph == 40
    # Must not compress narrower than the floor.
    assert pw >= 40


def test_plot_width_at_one_hundred_percent_cap():
    # 10 one-char categories, content min 20. W=20 puts the plot on the
    # 100% ceiling; it must not grow past it.
    cats = ",".join(f"{i}" for i in range(10))
    vals = ",".join("1" for _ in range(10))
    chart = parse(f"xychart-beta\n    x-axis [{cats}]\n    bar [{vals}]\n")
    out = render(chart, use_ascii=False, width=20)
    pw = _inner_plot_width(out)
    ph = _plot_height(out)
    assert pw == 20
    assert ph == 10  # 2:1 at the ceiling
    assert pw <= 20


def test_plot_height_grows_slower_than_width_between_bounds():
    # W=30, 10 one-char cats, content=20: between floor 15 and ceil 30.
    cats = ",".join(f"{i}" for i in range(10))
    vals = ",".join("1" for _ in range(10))
    chart = parse(f"xychart-beta\n    x-axis [{cats}]\n    bar [{vals}]\n")
    out = render(chart, use_ascii=False, width=30)
    pw = _inner_plot_width(out)
    ph = _plot_height(out)
    assert pw == 20
    assert ph == 15  # frozen at the 50%-of-W floor, so height < width
    assert pw / ph <= 2.0 + 1e-9


def test_plot_overflows_when_fifty_percent_floor_cannot_fit_labels():
    # 10 long labels, min_col ~ 10, content ~ 100. W=20 cannot hold them
    # even at 100%, so the plot overflows and scrolls (VIEWMD-0018).
    cats = ",".join(f"Category{i}" for i in range(10))
    vals = ",".join("1" for _ in range(10))
    chart = parse(f"xychart-beta\n    x-axis [{cats}]\n    bar [{vals}]\n")
    out = render(chart, use_ascii=False, width=20)
    pw = _inner_plot_width(out)
    assert pw > 20


def test_plot_geometry_unit():
    # Directly pins the three requirement-8 bounds.
    col, pw, rows = _plot_geometry(4, 3, 80)
    assert pw == 40 and rows == 40 and col == 10
    col, pw, rows = _plot_geometry(10, 2, 20)
    assert pw == 20 and rows == 10 and col == 2
    col, pw, rows = _plot_geometry(10, 2, 30)
    assert pw == 20 and rows == 15 and col == 2
    # Snapping to whole columns must not drop back below the 50% floor.
    col, pw, rows = _plot_geometry(13, 6, 200)
    assert pw >= 100
    assert pw <= 200


def test_cli_width_reaches_the_renderer():
    # Same plumbing regression pie/quadrant already pin: `width` must not
    # be dropped in favour of a freshly-queried terminal size.
    md = f"```mermaid\n{_SALES}```\n"
    narrow = render_markdown(md, width=40, color=False)
    wide = render_markdown(md, width=80, color=False)
    assert narrow != wide


