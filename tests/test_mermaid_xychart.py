def test_bar_glyph_precise_sales_examples():
    # Issue mockup: step 10, row V's band is [V-5, V+5).
    assert _bar_glyph(42.5, 40, 10, use_ascii=False) == "▆"
    assert _bar_glyph(67.3, 70, 10, use_ascii=False) == "▂"
    assert _bar_glyph(23.8, 20, 10, use_ascii=False) == "▇"
    assert _bar_glyph(89.1, 90, 10, use_ascii=False) == "▃"


def test_bar_glyph_exact_tick_is_half_block():
    assert _bar_glyph(40, 40, 10, use_ascii=False) == "▄"
    assert _bar_glyph(40, 30, 10, use_ascii=False) == "█"
    assert _bar_glyph(40, 50, 10, use_ascii=False) == " "


def test_bar_glyph_every_eighth():
    # Row V=4, step=1, band [3.5, 4.5). h = 3.5 + k/8 for k=1..8.
    expected = "▁▂▃▄▅▆▇█"
    for k, ch in enumerate(expected, start=1):
        h = 3.5 + k / 8
        assert _bar_glyph(h, 4, 1, use_ascii=False) == ch, (k, h)


def test_bar_glyph_ascii_collapses_to_one_fill():
    assert _bar_glyph(40, 40, 10, use_ascii=True) == "#"
    assert _bar_glyph(40, 30, 10, use_ascii=True) == "#"
    assert _bar_glyph(40, 50, 10, use_ascii=True) == " "


