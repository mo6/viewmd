def test_xychart_fence_is_recognized_end_to_end():
    text = "```mermaid\n" + _SALES + "```\n"
    got = render_mermaid_blocks(text, width=80)
    assert "```mermaid\n" not in got
    assert f"```{MERMAID_RENDERED_INFO}\n" in got
    assert "Sales" in got
    assert "│" in got


def test_bare_xychart_fence_is_recognized_end_to_end():
    text = "```mermaid\nxychart\n    x-axis [A, B]\n    bar [1, 2]\n```\n"
    got = render_mermaid_blocks(text, width=80)
    assert f"```{MERMAID_RENDERED_INFO}\n" in got


def test_malformed_dataset_length_falls_back_to_raw_fence():
    text = "```mermaid\nxychart-beta\n    x-axis [A, B, C]\n    bar [1, 2]\n```\n"
    assert render_mermaid_blocks(text) == text
    with pytest.raises(mermaid.MermaidError):
        mermaid.render("xychart-beta\n    x-axis [A, B, C]\n    bar [1, 2]\n")


def test_multi_series_falls_back_to_raw_fence():
    text = (
        "```mermaid\n"
        "xychart\n"
        '    title "Different Colors in xyChart"\n'
        '    x-axis "categoriesX" ["Category 1", "Category 2", "Category 3", "Category 4"]\n'
        '    y-axis "valuesY" 0 --> 50\n'
        "    line [10,20,30,40]\n"
        "    bar [20,30,25,35]\n"
        "    bar [15,25,20,30]\n"
        "    line [5,15,25,35]\n"
        "```\n"
    )
    assert render_mermaid_blocks(text) == text


def test_numeric_x_axis_falls_back_to_raw_fence():
    text = "```mermaid\nxychart-beta\n    x-axis 0 --> 10\n    bar [1, 2]\n```\n"
    assert render_mermaid_blocks(text) == text


def test_horizontal_still_renders_bottom_up():
    src = (
        "xychart-beta horizontal\n"
        "    x-axis [Q1, Q2]\n"
        "    y-axis 0 --> 10\n"
        "    bar [4, 8]\n"
    )
    out = render(parse(src), use_ascii=False, width=20)
    # Categories along the bottom, not down the left edge.
    assert out.splitlines()[-1].strip().startswith("Q1")
    assert "Q2" in out.splitlines()[-1]


def test_auto_scale_uses_data_min_max():
    chart = parse("xychart-beta\n    x-axis [A, B]\n    bar [40, 80]\n")
    out = render(chart, use_ascii=False, width=20)
    # Top tick is the data max (or close); bottom is the data min.
    ticks = [ln.split()[0] for ln in out.splitlines() if "│" in ln or "└" in ln]
    assert "80" in ticks[0]
    assert "40" in ticks[-1]


def test_existing_diagram_types_unchanged():
    # Requirement 10: a pie fence still renders as a pie, not an xychart.
    text = '```mermaid\npie\n    "A" : 1\n    "B" : 1\n```\n'
    got = render_mermaid_blocks(text)
    assert "┃" in got
    assert "xychart" not in got
