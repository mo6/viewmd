def test_ascii_mode_collapses_bar_and_line_glyphs():
    chart = parse(
        "xychart-beta\n"
        "    x-axis [Q1, Q2, Q3, Q4]\n"
        "    y-axis 0 --> 100\n"
        "    bar  [40, 60, 80, 100]\n"
        "    line [60, 80, 100, 120]\n"
    )
    out = render(chart, use_ascii=True, width=80)
    for ch in "█▁▂▃▄▅▆▇╭╮╰╯│─└┬":
        assert ch not in out
    assert "#" in out
    assert "+" in out
    assert "-" in out
    assert "|" in out


