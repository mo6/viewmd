"""Tests for the XY-chart renderer (VIEWMD-0048).

No upstream reference implementation to differentially test against (like
pie/quadrant, unlike flowchart/sequence/ER) -- termaid's own rendering was
a useful cross-check during design (see the issue's Design notes), not an
oracle, and it uses a different (edge-anchored, two-level) bar rounding
and a diagonal line style. Fixtures in tests/fixtures/mermaid_xychart/ are
hand-authored/generated by this renderer itself and visually verified.
"""

from __future__ import annotations

from pathlib import Path

import pytest

import viewmd.mermaid as mermaid
from viewmd.mermaid.preprocess import MERMAID_RENDERED_INFO, render_mermaid_blocks
from viewmd.mermaid.xychart.parser import parse
from viewmd.mermaid.xychart.renderer import _bar_glyph, _plot_geometry, render
from viewmd.render import render_markdown

FIXTURES = Path(__file__).parent / "fixtures" / "mermaid_xychart"


def _inner_plot_width(out: str) -> int:
    widths = []
    for line in out.splitlines():
        if "│" in line:
            widths.append(len(line.split("│", 1)[1]))
        elif "|" in line and not line.strip().startswith("|"):
            # ascii mode
            parts = line.split("|", 1)
            if len(parts) == 2:
                widths.append(len(parts[1]))
    return max(widths) if widths else 0


def _plot_height(out: str) -> int:
    n = 0
    for line in out.splitlines():
        if "│" in line or (
            "|" in line and not line.strip().startswith("|") and "---" not in line
        ):
            n += 1
    return n


def _row_for_tick(out: str, tick: str) -> str:
    for line in out.splitlines():
        if line.lstrip().startswith(tick + " ") or line.lstrip().startswith(tick + " │"):
            if "│" in line:
                return line
    raise AssertionError(f"no row labelled {tick!r} in:\n{out}")


